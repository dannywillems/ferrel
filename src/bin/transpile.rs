//! `ferrel-transpile`: the command-line driver for the Rust-subset transpiler.
//!
//! Usage:
//!
//! ```text
//!   ferrel-transpile INPUT.rs [-o OUTPUT.el] [--byte-compile] [--native-compile]
//! ```
//!
//! It reads `INPUT.rs`, lowers the supported Rust subset into the `Sexp` IR, and
//! writes the rendered Elisp to `OUTPUT.el` (default: the input path with its
//! extension changed to `.el`). The output is a bare sequence of top-level forms
//! prefixed with a `lexical-binding: t` cookie, not a full `package.el` skeleton:
//! the transpiler lowers exactly the forms the user wrote, in order.
//!
//! `--byte-compile` and `--native-compile` shell out to Emacs after writing the
//! file; they are guarded behind their flags and are no-ops otherwise.

use std::{path::PathBuf, process::Command};

use ferrel::transpile_file;

/// Parsed command-line arguments.
struct Args {
    input: PathBuf,
    output: Option<PathBuf>,
    byte_compile: bool,
    native_compile: bool,
}

const USAGE: &str =
    "usage: ferrel-transpile INPUT.rs [-o OUTPUT.el] [--byte-compile] [--native-compile]";

fn main() {
    if let Err(msg) = run() {
        eprintln!("ferrel-transpile: {msg}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let args = parse_args()?;

    let forms =
        transpile_file(&args.input).map_err(|e| format!("{}: {e}", args.input.display()))?;

    let output = args
        .output
        .clone()
        .unwrap_or_else(|| args.input.with_extension("el"));

    let text = render_file(&output, &forms);
    std::fs::write(&output, &text)
        .map_err(|e| format!("cannot write {}: {e}", output.display()))?;
    eprintln!("wrote {}", output.display());

    if args.byte_compile {
        byte_compile(&output)?;
    }
    if args.native_compile {
        native_compile(&output)?;
    }
    Ok(())
}

/// Hand-rolled argument parsing (no clap).
fn parse_args() -> Result<Args, String> {
    let mut input: Option<PathBuf> = None;
    let mut output: Option<PathBuf> = None;
    let mut byte_compile = false;
    let mut native_compile = false;

    let mut it = std::env::args().skip(1);
    while let Some(arg) = it.next() {
        match arg.as_str() {
            "-h" | "--help" => {
                println!("{USAGE}");
                std::process::exit(0);
            }
            "-o" | "--output" => {
                let path = it
                    .next()
                    .ok_or_else(|| format!("{arg} requires a path argument\n{USAGE}"))?;
                output = Some(PathBuf::from(path));
            }
            "--byte-compile" => byte_compile = true,
            "--native-compile" => native_compile = true,
            other if other.starts_with('-') => {
                return Err(format!("unknown flag `{other}`\n{USAGE}"));
            }
            other => {
                if input.is_some() {
                    return Err(format!("unexpected extra argument `{other}`\n{USAGE}"));
                }
                input = Some(PathBuf::from(other));
            }
        }
    }

    let input = input.ok_or_else(|| format!("no input file given\n{USAGE}"))?;
    Ok(Args {
        input,
        output,
        byte_compile,
        native_compile,
    })
}

/// Render the forms into a complete `.el` file body with a header cookie.
fn render_file(output: &std::path::Path, forms: &[ferrel::Sexp]) -> String {
    let stem = output
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("output");
    let mut text = format!(
        ";;; {stem}.el --- generated by ferrel-transpile -*- lexical-binding: t; -*-\n\n\
         ;;; Commentary:\n\
         ;; This file was generated from Rust by ferrel-transpile.\n\
         ;; Do not edit by hand: edit the Rust source and regenerate.\n\n\
         ;;; Code:\n\n"
    );
    for form in forms {
        text.push_str(&form.render());
        text.push_str("\n\n");
    }
    text.push_str(&format!("(provide '{stem})\n;;; {stem}.el ends here\n"));
    text
}

/// Byte-compile the output file with `emacs --batch`, treating warnings as
/// errors. The Emacs binary is taken from `$EMACS` or defaults to `emacs`.
fn byte_compile(file: &std::path::Path) -> Result<(), String> {
    let emacs = std::env::var("EMACS").unwrap_or_else(|_| "emacs".to_string());
    let status = Command::new(&emacs)
        .arg("--batch")
        .args(["--eval", "(setq byte-compile-error-on-warn t)"])
        .arg("-f")
        .arg("batch-byte-compile")
        .arg(file)
        .status()
        .map_err(|e| format!("failed to run `{emacs}`: {e}"))?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("byte-compilation of {} failed", file.display()))
    }
}

/// Native-compile the output file with `emacs --batch` and `native-compile`.
fn native_compile(file: &std::path::Path) -> Result<(), String> {
    let emacs = std::env::var("EMACS").unwrap_or_else(|_| "emacs".to_string());
    let eval = format!("(native-compile {:?})", file.to_string_lossy());
    let status = Command::new(&emacs)
        .arg("--batch")
        .args(["--eval", &eval])
        .status()
        .map_err(|e| format!("failed to run `{emacs}`: {e}"))?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("native-compilation of {} failed", file.display()))
    }
}
